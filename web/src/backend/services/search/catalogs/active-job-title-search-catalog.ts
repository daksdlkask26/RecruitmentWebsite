export const activeJobTitleSearchCatalog: readonly OccupationSearchEntry[] =
  activeTitleGroups.map((group) => {
    return {
      occupationId: group.occupationId,
      industryCode: group.industryCode,
      categoryIds: group.categoryIds,
      labels: group.labels,
      aliases: group.aliases,
      abbreviations: [],
      relatedTitles: {
        vi: [
          ...new Set(
            group.titles.flatMap((title) => [
              ...(bilingualTitleTranslations[title]
                ? [bilingualTitleTranslations[title]]
                : []),
              ...(bilingualTitleAliases[title] ?? []),
            ]),
          ),
        ],
        en: group.titles,
      },
      titleFacetMappings: [
        ...(group.titleFacetMappings ?? []),
        ...group.titles.flatMap((title) => {
          const translation = bilingualTitleTranslations[title];
          if (!translation) return [];
          const mapping = group.titleFacetMappings?.find(
            (candidate) => candidate.phrase === title,
          );
          return mapping
            ? [{ phrase: translation, facetIds: mapping.facetIds }]
            : [];
        }),
      ],
      rankingSkills: [],
      irregularAliases: [],
      exclusions: [],
    };
  });

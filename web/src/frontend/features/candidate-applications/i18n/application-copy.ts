export type ApplicationLocale = "en" | "vi";

export function applicationErrorMessage(
  locale: ApplicationLocale,
  cause: unknown,
  fallback: string,
  trustedMessages: readonly string[] = [],
): string {
  if (!(cause instanceof Error) || !cause.message) return fallback;
  if (locale === "en" || trustedMessages.includes(cause.message)) {
    return cause.message;
  }
  return fallback;
}


type WidenApplicationCopy<T> = T extends (...args: infer Args) => unknown
  ? (...args: Args) => string
  : T extends string
    ? string
    : T extends Record<string, unknown>
      ? { [Key in keyof T]: WidenApplicationCopy<T[Key]> }
      : T;

